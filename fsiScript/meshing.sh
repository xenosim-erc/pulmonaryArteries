if [[ -n "$case_name" && "$case_name" != "." && "$case_name" != ".." &&
      "$output_dir" == "$case_files_dir" && -d "$case_files_dir" && -t 0 ]]; then
    read -r -p "Remove the intermediate meshing case '$case_files_dir'? [y/N]: " remove_case
    case "$remove_case" in
        y|Y|yes|YES|Yes)
            rm -rf -- "$case_files_dir"
            echo "Removed intermediate meshing case: $case_files_dir"
            ;;
        *)
            echo "Retained intermediate meshing case: $case_files_dir"
            ;;
    esac
elif [[ "$output_dir" != "$case_files_dir" ]]; then
    echo "Retained custom meshing output directory: $output_dir"
fi

echo
echo "Run case ready: $run_case"
echo "Settings recorded in: $params_file"
echo
echo "Next steps:"
echo "  cd $run_case"
echo "  checkMesh -region solid    # look for self-intersection at the bifurcations"
echo "  sbatch run.slurm"
echo
echo "If the solid self-intersects, rerun with a smaller --extrusion-percentage"
echo "or more smoothing."
